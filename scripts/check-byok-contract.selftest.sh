#!/usr/bin/env bash
# Self-test suite for the BYOK contract gate's plan 26 rules (R6 decision
# preset data, R7 decision secret ids). Fixtures are materialized at runtime
# into mktemp -d — no committed fixture trees, so vendoring four copies stays
# cheap and byte-identity stays meaningful (same discipline as
# check-family-convergence.selftest.sh).
#
# Every case plants a tree, copies the gate INTO it (the gate resolves ROOT
# from its own location, so testing a tree means running the tree's copy),
# and asserts both the exit code and which rule fired. R1–R5 have no cases
# here: they are unchanged plan 17 rules pinned by the per-repo suites.
#
# Usage: bash check-byok-contract.selftest.sh
# Exit: non-zero on any surprise; one ok/FAIL line per case.
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
GATE_NAME="check-byok-contract.sh"
GATE="$HERE/$GATE_NAME"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

PASS=0
FAIL=0

ok_case()   { PASS=$((PASS + 1)); echo "ok   $1"; }
fail_case() { FAIL=$((FAIL + 1)); echo "FAIL $1"; echo "$2" | sed 's/^/     /'; }

# run_gate DIR -- run DIR's vendored gate copy; sets RUN_OUT/RUN_RC.
run_gate() {
  RUN_OUT="$(cd "$1" && bash "$1/scripts/$GATE_NAME" 2>&1)"
  RUN_RC=$?
}

# expect NAME WANT_RC WANT_RE [REJECT_RE] -- assert on RUN_OUT/RUN_RC.
expect() {
  local name="$1" want_rc="$2" want_re="$3" reject_re="${4:-}" bad=""
  [ "$RUN_RC" != "$want_rc" ] && bad="rc=$RUN_RC want=$want_rc"
  grep -qE -- "$want_re" <<<"$RUN_OUT" || bad="$bad; missing /$want_re/"
  if [ -n "$reject_re" ] && grep -qE -- "$reject_re" <<<"$RUN_OUT"; then
    bad="$bad; unexpected /$reject_re/"
  fi
  if [ -n "$bad" ]; then fail_case "$name" "$bad"$'\n'"$RUN_OUT"; else ok_case "$name"; fi
}

vendor_gate() {  # DIR -- copy the gate into a tree's scripts/ dir
  mkdir -p "$1/scripts"
  cp "$GATE" "$1/scripts/$GATE_NAME"
}

# ---------------------------------------------------------------------------
# R6 cases
# ---------------------------------------------------------------------------

# R6 pass: full schema-2 wave — canonical + sync script vendored, generated
# TS produced by actually running the vendored sync (node required).
T="$WORK/r6-pass"; vendor_gate "$T"
mkdir -p "$T/contracts"
cp "$HERE/../contracts/ai-presets.json" "$T/contracts/ai-presets.json"
cp "$HERE/sync-ai-presets.mjs" "$T/scripts/sync-ai-presets.mjs"
mkdir -p "$T/src/shared/ai"
if node "$T/scripts/sync-ai-presets.mjs" --ts "$T/src/shared/ai/providerPresets.generated.ts" >/dev/null 2>&1; then
  run_gate "$T"
  expect "R6 pass: schema-2 canonical + generated decision data" 0 \
    'R6 canonical presets are on the schema-2 decision wave|R6 generated TS module carries the decision fields' \
    'R6 .*drift|R6 .*lacks'
else
  fail_case "R6 pass: schema-2 canonical + generated decision data" "node unavailable or sync failed"
fi

# R6 fail (stale canonical): schema 1 vendored without the sync script.
T="$WORK/r6-stale-canonical"; vendor_gate "$T"
mkdir -p "$T/contracts"
printf '{\n  "schema": 1,\n  "presetOrder": [],\n  "presets": {}\n}\n' > "$T/contracts/ai-presets.json"
run_gate "$T"
expect "R6 fail: pre-decision schema-1 canonical" 1 'R6 contracts/ai-presets.json is schema 1 \(pre-decision\)'

# R6 fail (stale pair): schema 2 canonical, generated TS stripped of the
# decision fields, no sync script vendored (R1 skipped — isolates R6).
T="$WORK/r6-stale-pair"; vendor_gate "$T"
mkdir -p "$T/contracts" "$T/src/shared/ai"
cp "$HERE/../contracts/ai-presets.json" "$T/contracts/ai-presets.json"
printf '// GENERATED by sync-ai-presets.mjs from contracts/ai-presets.json (schema 2) — DO NOT EDIT.\nexport const PROVIDER_PRESET_DATA = {};\n' > "$T/src/shared/ai/providerPresets.generated.ts"
run_gate "$T"
expect "R6 fail: generated module stripped of decision fields" 1 'R6 .*lacks the decision fields'

# ---------------------------------------------------------------------------
# R7 cases
# ---------------------------------------------------------------------------

# R7 pass: provider-templated secret builder only (the legacy openrouter:key
# exemption is gone — the id is a plain violation now).
T="$WORK/r7-pass"; vendor_gate "$T"
mkdir -p "$T/src/main/services"
cat > "$T/src/main/services/SecretService.ts" <<'EOF'
export const providerSecretKey = (providerId: string): string => `provider:${providerId}`;
EOF
run_gate "$T"
expect "R7 pass: provider ids only" 0 'R7 no decision secrets outside'

# R7 fail: the retired legacy 'openrouter:key' id (plan 26 Phase 1 S2 removed
# the exemption — it must fail like any bespoke id).
T="$WORK/r7-legacy-openrouter"; vendor_gate "$T"
mkdir -p "$T/src/shared/ai"
cat > "$T/src/shared/ai/decisions.ts" <<'EOF'
export const JEV_SECRET_ID = 'openrouter:key';
EOF
run_gate "$T"
expect "R7 fail: legacy 'openrouter:key' is no longer exempt" 1 "R7 decision secret id 'openrouter:key' is not a provider:<id> id"

# R7 fail: bespoke decision secret id.
T="$WORK/r7-fail"; vendor_gate "$T"
mkdir -p "$T/src/main/ai/decide"
cat > "$T/src/main/ai/decide/registry.ts" <<'EOF'
const JEV_SECRET_ID = 'jev:key';
EOF
run_gate "$T"
expect "R7 fail: bespoke 'jev:key' decision secret id" 1 "R7 decision secret id 'jev:key' is not a provider:<id> id"

# R7 fail (python): bespoke decision secret id under backend/app.
T="$WORK/r7-fail-py"; vendor_gate "$T"
mkdir -p "$T/backend/app/ai/decide"
cat > "$T/backend/app/ai/decide/registry.py" <<'EOF'
SECRET_ID = "decision:jev"
EOF
run_gate "$T"
expect "R7 fail: python 'decision:jev' secret id" 1 "R7 decision secret id 'decision:jev' is not a provider:<id> id"

# R7 pass (python): provider-templated secret id.
T="$WORK/r7-pass-py"; vendor_gate "$T"
mkdir -p "$T/backend/app/ai/decide"
cat > "$T/backend/app/ai/decide/registry.py" <<'EOF'
secret_id = f"provider:{provider_id}"
EOF
run_gate "$T"
expect "R7 pass: python provider-templated secret id" 0 'R7 no decision secrets outside provider:<id> ids'

echo "byok gate selftest: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ]
