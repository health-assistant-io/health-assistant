#!/usr/bin/env node
// sync-task-registry — project the ONE AI task registry into generated code.
//
// Source of truth: backend/app/ai/providers/task_registry.py (Python).
// Projections (never hand-edited):
//   * backend/app/ai/providers/task_types.py   (the TaskType StrEnum)
//   * frontend/src/generated/taskRegistry.ts   (the AI-settings task list)
//
// Same sync-and-gate pattern as sync-ai-presets.mjs (ADR-0031): the data is
// generated once, committed, and a drift gate (scripts/check-task-registry.sh)
// compares the committed projections against the registry.
//
// Usage:
//   node scripts/sync-task-registry.mjs --ts <out.ts>
//   node scripts/sync-task-registry.mjs --py <out.py>
//   node scripts/sync-task-registry.mjs --check <ts-path>
//   node scripts/sync-task-registry.mjs --check-py <py-path>
//
// The registry is loaded BY PATH in a Python subprocess so no application
// settings, database or package side effects are required.

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const registryPath = join(root, 'backend', 'app', 'ai', 'providers', 'task_registry.py');

const SUPPORTED_SCHEMA = 1;

function fail(code, message) {
  console.error(`sync-task-registry: ${message}`);
  process.exit(code);
}

function pythonExecutable() {
  const candidates = [
    process.env.TASK_REGISTRY_PYTHON,
    join(root, 'backend', 'venv', 'bin', 'python'),
    join(root, 'backend', '.venv', 'bin', 'python'),
    'python3',
    'python',
  ].filter(Boolean);
  for (const candidate of candidates) {
    if (candidate !== 'python3' && candidate !== 'python' && !existsSync(candidate)) continue;
    try {
      execFileSync(candidate, ['--version'], { stdio: 'ignore' });
      return candidate;
    } catch {
      // try the next candidate
    }
  }
  fail(2, 'no Python interpreter found — set TASK_REGISTRY_PYTHON');
}

const LOADER = `
import importlib.util, json, sys
spec = importlib.util.spec_from_file_location("ai_task_registry", sys.argv[1])
module = importlib.util.module_from_spec(spec)
sys.modules["ai_task_registry"] = module
spec.loader.exec_module(module)
print(json.dumps(module.registry_payload()))
`;

function loadRegistry() {
  if (!existsSync(registryPath)) fail(2, `registry not found at ${registryPath}`);
  let raw;
  try {
    raw = execFileSync(pythonExecutable(), ['-c', LOADER, registryPath], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
  } catch (error) {
    fail(2, `could not load the registry: ${error.stderr || error.message}`);
  }
  const payload = JSON.parse(raw);
  if (payload.schema !== SUPPORTED_SCHEMA) {
    fail(2, `schema ${payload.schema} not supported (supported: ${SUPPORTED_SCHEMA}) — extend the emitters first`);
  }
  return payload;
}

const q = (value) => JSON.stringify(value);
const orderedUnique = (values) => [...new Set(values)];

function generateTs(payload) {
  const tasks = payload.tasks;
  const capabilities = orderedUnique(tasks.map((task) => task.capability));
  const triggers = orderedUnique(tasks.map((task) => task.trigger));
  const phiClasses = orderedUnique(tasks.map((task) => task.phiClass));
  const routes = [...orderedUnique(tasks.map((task) => task.route))].sort();

  const entries = tasks
    .map(
      (task) =>
        [
          '  {',
          `    id: ${q(task.id)},`,
          `    labelKey: ${q(task.labelKey)},`,
          `    capability: ${q(task.capability)},`,
          `    trigger: ${q(task.trigger)},`,
          `    phiClass: ${q(task.phiClass)},`,
          `    acceptsPriority: ${task.acceptsPriority},`,
          `    decisionKinds: [${task.decisionKinds.map(q).join(', ')}],`,
          `    enabled: ${task.enabled},`,
          `    route: ${q(task.route)},`,
          `    capabilityDefault: ${task.capabilityDefault},`,
          '  },',
        ].join('\n'),
    )
    .join('\n');

  const list = (values) => values.map((value) => `  ${q(value)},`).join('\n');

  return `// GENERATED by sync-task-registry.mjs from backend/app/ai/providers/task_registry.py — DO NOT EDIT.
// Canonical source: backend/app/ai/providers/task_registry.py
// Regenerate: node scripts/sync-task-registry.mjs --ts frontend/src/generated/taskRegistry.ts
// Drift gate: scripts/check-task-registry.sh + backend/tests/test_ai_task_registry.py

export const AI_TASK_REGISTRY_SCHEMA = ${payload.schema};

export type AiTaskCapability = ${capabilities.map(q).join(' | ')};
export type AiTaskTrigger = ${triggers.map(q).join(' | ')};
export type AiTaskPhiClass = ${phiClasses.map(q).join(' | ')};
export type AiTaskRoute = ${routes.map(q).join(' | ')};

export interface AiTaskDef {
  readonly id: string;
  readonly labelKey: string;
  readonly capability: AiTaskCapability;
  readonly trigger: AiTaskTrigger;
  readonly phiClass: AiTaskPhiClass;
  readonly acceptsPriority: boolean;
  readonly decisionKinds: readonly string[];
  readonly enabled: boolean;
  readonly route: AiTaskRoute;
  readonly capabilityDefault: boolean;
}

export const AI_TASKS: readonly AiTaskDef[] = [
${entries}
];

export const AI_TASK_DEFS: Readonly<Record<string, AiTaskDef>> = Object.fromEntries(
  AI_TASKS.map((task) => [task.id, task]),
);

export const AI_TASK_IDS: readonly string[] = AI_TASKS.map((task) => task.id);

/** The four decision kind slots (specialist assignments). */
export const AI_DECISION_TASK_IDS: readonly string[] = [
${list(payload.decisionTaskIds)}
];

/** ADR-0036: the decision default slot each unset kind inherits. */
export const AI_DECISION_DEFAULT_TASK_ID = ${q(payload.decisionDefaultId)};

/** Capability defaults — the last hop of every resolution chain. */
export const AI_CAPABILITY_DEFAULT_TASK_IDS: readonly string[] = [
${list(tasks.filter((task) => task.capabilityDefault).map((task) => task.id))}
];

export function isDecisionTask(taskId: string): boolean {
  return taskId === AI_DECISION_DEFAULT_TASK_ID || AI_DECISION_TASK_IDS.includes(taskId);
}
`;
}

function generatePy(payload) {
  const members = payload.tasks
    .map((task) => `    ${task.id.toUpperCase()} = ${q(task.id)}`)
    .join('\n');
  const decisionIds = payload.decisionTaskIds.map((id) => `    ${q(id)},`).join('\n');

  return `"""GENERATED by sync-task-registry.mjs from app/ai/providers/task_registry.py.

DO NOT EDIT. The TaskType members are the registry ids:
change the registry and regenerate with
'node scripts/sync-task-registry.mjs --py backend/app/ai/providers/task_types.py'.
The import path stays stable through the 'app.ai.providers.enums' re-export.
"""

from __future__ import annotations

import enum

_DECISION_TASK_IDS: tuple[str, ...] = (
${decisionIds}
)

_DECISION_DEFAULT_ID = ${q(payload.decisionDefaultId)}


class TaskType(enum.StrEnum):
    """Canonical AI task types (one member per TaskDef registry id)."""

${members}

    @classmethod
    def all_values(cls) -> list[str]:
        """Ordered list of task_type string values (registry declaration order)."""
        return [member.value for member in cls]

    @classmethod
    def from_string(cls, value: str | None) -> TaskType | None:
        """Tolerant lookup; returns None for unknown values."""
        if value is None:
            return None
        try:
            return cls(value)
        except ValueError:
            return None

    @classmethod
    def is_decision_default(cls, value: str | None) -> bool:
        """True for the 'decision' default slot (ADR-0036)."""
        return value == _DECISION_DEFAULT_ID

    @classmethod
    def is_decision(cls, value: str | None) -> bool:
        """True for the four 'decision_*' kind slots (ADR-0032).

        Decision slots live in the same table as every other assignment but
        obey D4 slot separation: they resolve decision-capable models only and
        never fall back to the 'default' task.
        """
        return value in _DECISION_TASK_IDS
`;
}

function write(mode, path, content) {
  writeFileSync(path, content);
  console.log(`sync-task-registry: wrote ${path} (${mode})`);
}

const args = process.argv.slice(2);
const mode = args[0];
const target = args[1];

if (!mode) {
  console.log('usage: sync-task-registry.mjs --ts <out.ts> | --py <out.py> | --check <ts> | --check-py <py>');
  fail(1, 'missing mode');
}

if (mode === '--ts') {
  if (!target) fail(1, '--ts requires an output path');
  write('ts', target, generateTs(loadRegistry()));
} else if (mode === '--py') {
  if (!target) fail(1, '--py requires an output path');
  write('py', target, generatePy(loadRegistry()));
} else if (mode === '--check' || mode === '--check-py') {
  if (!target) fail(1, `${mode} requires the generated file path`);
  const generated = mode === '--check' ? generateTs(loadRegistry()) : generatePy(loadRegistry());
  const current = readFileSync(target, 'utf8');
  if (current !== generated) {
    const regenerate =
      mode === '--check'
        ? `node scripts/sync-task-registry.mjs --ts ${target}`
        : `node scripts/sync-task-registry.mjs --py ${target}`;
    fail(
      1,
      `drift: ${target} does not match backend/app/ai/providers/task_registry.py — regenerate (${regenerate})`,
    );
  }
  console.log(`sync-task-registry: no drift (${target})`);
} else {
  fail(1, `unknown mode ${mode}`);
}
