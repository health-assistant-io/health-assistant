#!/usr/bin/env bash
# check-task-registry — the AI task registry drift gate (plan 4 W1).
#
# One task list exists: backend/app/ai/providers/task_registry.py. Everything
# else is a generated projection. This gate fails when a projection drifts, when
# a hand-maintained copy reappears, or when a task has no UI label.
#
# Rules:
#   R1  frontend/src/generated/taskRegistry.ts matches the registry (sync --check)
#   R1b backend/app/ai/providers/task_types.py matches the registry (sync --check-py)
#   R2  no hand-maintained task structures: TASK_REQUIRED_CAPABILITY /
#       _SLOT_TASK_TYPES / an OTHER_TASKS list under app/ or src/
#   R3  every registry label_key resolves in every shipped locale
#   R4  non-LLM engine tasks (RxNorm / analytics) never reappear in the AI layer
#       or the AI-settings surface
#
# The DB side (ai_task_defs seed ≡ registry, migration rows ≡ registry) is
# pinned by backend/tests/test_ai_task_registry.py — a gate needs a migrated DB,
# so it stays in the suite rather than here.
#
# Usage: check-task-registry.sh [--self]   (run from anywhere; ROOT is probed)
set -uo pipefail

for arg in "$@"; do
  case "$arg" in
    --self) ;;
    *) echo "unknown argument: $arg" >&2; exit 2 ;;
  esac
done

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
FAIL=0

note() { echo "  - $1"; }
bad()  { echo "  ✗ $1" >&2; FAIL=1; }
good() { echo "  ✓ $1"; }

echo "task registry gate: $ROOT"

REGISTRY="$ROOT/backend/app/ai/providers/task_registry.py"
GENERATED_TS="$ROOT/frontend/src/generated/taskRegistry.ts"
GENERATED_PY="$ROOT/backend/app/ai/providers/task_types.py"
SYNC="$ROOT/scripts/sync-task-registry.mjs"

if [ ! -f "$REGISTRY" ]; then
  bad "R0 registry missing at backend/app/ai/providers/task_registry.py"
  echo "task registry: FAILURES above" >&2
  exit 1
fi
if ! command -v node >/dev/null 2>&1; then
  bad "R0 node is required to run the generator gate"
  echo "task registry: FAILURES above" >&2
  exit 1
fi

# R1 — generated TypeScript projection.
if [ -f "$GENERATED_TS" ]; then
  if head -1 "$GENERATED_TS" | grep -q "GENERATED by sync-task-registry"; then
    if node "$SYNC" --check "$GENERATED_TS" >/dev/null 2>&1; then
      good "R1 taskRegistry.ts matches the registry"
    else
      bad "R1 drift: frontend/src/generated/taskRegistry.ts does not match the registry (regenerate: node scripts/sync-task-registry.mjs --ts frontend/src/generated/taskRegistry.ts)"
    fi
  else
    bad "R1 $GENERATED_TS lacks the GENERATED header — it must come from the sync script"
  fi
else
  bad "R1 missing frontend/src/generated/taskRegistry.ts"
fi

# R1b — generated Python enum projection.
if [ -f "$GENERATED_PY" ]; then
  if head -1 "$GENERATED_PY" | grep -q "GENERATED by sync-task-registry"; then
    if node "$SYNC" --check-py "$GENERATED_PY" >/dev/null 2>&1; then
      good "R1b task_types.py matches the registry"
    else
      bad "R1b drift: backend/app/ai/providers/task_types.py does not match the registry (regenerate: node scripts/sync-task-registry.mjs --py backend/app/ai/providers/task_types.py)"
    fi
  else
    bad "R1b $GENERATED_PY lacks the GENERATED header — it must come from the sync script"
  fi
else
  bad "R1b missing backend/app/ai/providers/task_types.py"
fi

# R2 — the deleted hand-maintained structures must stay deleted.
R2_HITS="$(
  grep -rn "TASK_REQUIRED_CAPABILITY\|_SLOT_TASK_TYPES\|OTHER_TASKS" \
    "$ROOT/backend/app" "$ROOT/frontend/src" 2>/dev/null \
    | grep -v "task_registry.py" \
    | grep -v "generated/" \
    || true
)"
if [ -n "$R2_HITS" ]; then
  bad "R2 hand-maintained task structure reappeared (derive from the registry instead):"
  echo "$R2_HITS" >&2
else
  good "R2 no hand-maintained task maps/lists (registry is the one source)"
fi

# R3 — label keys resolve in every shipped locale.
LABEL_CHECK="$(ROOT="$ROOT" python3 - "$GENERATED_TS" <<'PY'
import json, os, re, sys

root = os.environ["ROOT"]
generated = open(sys.argv[1], encoding="utf-8").read()
label_keys = sorted(set(re.findall(r'labelKey: "([^"]+)"', generated)))
if not label_keys:
    print("no labelKey entries found in the generated registry")
    sys.exit(1)

locales_dir = os.path.join(root, "frontend", "src", "locales")
locales = sorted(
    name
    for name in os.listdir(locales_dir)
    if os.path.isfile(os.path.join(locales_dir, name, "common.json"))
)
if len(locales) < 2:
    print(f"expected at least 2 shipped locales, found {locales}")
    sys.exit(1)

problems = []
for locale in locales:
    data = json.load(open(os.path.join(locales_dir, locale, "common.json"), encoding="utf-8"))
    for key in label_keys:
        node = data
        for part in key.split("."):
            node = node.get(part) if isinstance(node, dict) else None
            if node is None:
                break
        if node is None:
            problems.append(f"{locale}: missing {key}")
print("\n".join(problems))
sys.exit(1 if problems else 0)
PY
)"
if [ $? -eq 0 ]; then
  good "R3 every registry label key resolves in every locale"
else
  bad "R3 label keys missing from a locale:"
  echo "$LABEL_CHECK" >&2
fi

# R4 — engine tasks are not AI tasks.
R4_HITS="$(
  grep -rnE "['\"](medication_interaction|anomaly_detection)['\"]" \
    "$ROOT/backend/app/ai" "$ROOT/frontend/src/api/aiConfig.ts" \
    "$ROOT/frontend/src/components/settings" 2>/dev/null \
    | grep -v "test" \
    || true
)"
if [ -n "$R4_HITS" ]; then
  bad "R4 non-LLM engine task referenced from the AI layer / AI settings (plan 4 W4):"
  echo "$R4_HITS" >&2
else
  good "R4 engine tasks (RxNorm/analytics) are not AI tasks"
fi

if [ "$FAIL" -eq 0 ]; then
  echo "task registry: OK"
else
  echo "task registry: FAILURES above" >&2
fi
exit "$FAIL"
