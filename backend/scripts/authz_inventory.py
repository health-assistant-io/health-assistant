#!/usr/bin/env python3
"""Route inventory CLI — enumerate, check, and document every API route.

Enumerates the routes of the FastAPI app (HTTP + WebSocket), pairs them with
the curated inventory at ``app/core/authz/route_inventory.json`` and the
permission catalog, and either validates the route gate or regenerates the
internal matrix (``docs/dev/AUTHZ_MATRIX.md``).

The matrix is an internal development doc and deliberately NOT part of the
public docs tree (plan D §2 — docs-tree carries public pages only).

Usage (from ``backend/``):

    uv run python scripts/authz_inventory.py check       # the CI gate
    uv run python scripts/authz_inventory.py list        # print routes+classes
    uv run python scripts/authz_inventory.py matrix      # write AUTHZ_MATRIX.md
    uv run python scripts/authz_inventory.py policies    # write AUTHZ_ROUTE_POLICIES.md
    uv run python scripts/authz_inventory.py propose     # print entries the
                                                         #   gate is missing

Run with the same env as the tests (``HA_ENV_FILE=.env.test``) so the route
set matches what CI enumerates.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

from app.core.authz import permissions as authz_permissions
from app.core.authz import roles as authz_roles
from app.core.authz.policy import RouteClass
from app.core.authz.route_gate import (
    INVENTORY_PATH,
    EnumeratedRoute,
    check_inventory,
    enumerate_routes,
    load_inventory,
)
from app.core.authz.route_policy import resolve_route_policy, resolve_route_rule

BACKEND_ROOT = Path(__file__).resolve().parent.parent
MATRIX_PATH = BACKEND_ROOT.parent / "docs" / "dev" / "AUTHZ_MATRIX.md"
POLICIES_PATH = BACKEND_ROOT.parent / "docs" / "dev" / "AUTHZ_ROUTE_POLICIES.md"

POLICIES_HEADER = """<!-- generated by backend/scripts/authz_inventory.py — do not edit by hand -->

# Route policies (internal review artifact)

Every route with its principal class, the permission the central gate
requires and the scope it must be held at — resolved from
`backend/app/core/authz/route_policy.py` (the declaration of record, ADR
0054 Phase 1b) against the route inventory (the class baseline).
`—` means the route is enforced by its class mechanism (public metadata,
auth bootstrap, token principals, WebSockets) or is auth-only self-service.
Regenerate with:

    cd backend && HA_ENV_FILE=.env.test uv run python scripts/authz_inventory.py policies

The file is an internal development surface — it is deliberately NOT in the
public docs tree.
"""

MATRIX_HEADER = """<!-- generated by backend/scripts/authz_inventory.py — do not edit by hand -->

# Authorization matrix (internal)

Generated from the permission catalog (`backend/app/core/authz/`) and the
route inventory (`backend/app/core/authz/route_inventory.json`). ADR 0054
records the model; this file is its generated view. Regenerate with:

    cd backend && HA_ENV_FILE=.env.test uv run python scripts/authz_inventory.py matrix

The matrix is an internal development surface — it is deliberately NOT in the
public docs tree.
"""


def _enumerate() -> list[EnumeratedRoute]:
    from app.main import app

    return list(enumerate_routes(app.routes))


def _entry_map(inventory: dict) -> dict[str, dict]:
    return {entry["route"]: entry for entry in inventory["entries"]}


def _route_class(route: EnumeratedRoute, entries: dict[str, dict]) -> str:
    if route.declared is not None:
        return route.declared.route_class.value
    return entries[route.key]["route_class"]


def _resolved_cells(route: EnumeratedRoute, entries: dict[str, dict]) -> tuple[str, str, str]:
    """(class, permission, scope) resolved for one route — ``—`` when absent."""
    route_class = _route_class(route, entries)
    policy = resolve_route_policy(route.method, route.path, route_class)
    if policy is None:
        return route_class, "UNRESOLVED", "UNRESOLVED"
    permission = policy.permission.value if policy.permission else "—"
    scope = policy.scope.value if policy.scope else ("—" if policy.permission is None else "UNSET")
    return route_class, permission, scope


def cmd_check() -> int:
    enumerated = _enumerate()
    inventory = load_inventory()
    violations = check_inventory(enumerated, inventory)
    declared = sum(1 for route in enumerated if route.declared is not None)
    print(
        f"route gate: {len(enumerated)} routes, {len(inventory['entries'])} allowlist "
        f"entries, {declared} declared policies, {len(inventory['retired'])} retired keys"
    )
    if violations:
        print("route gate: FAIL\n")
        for violation in violations:
            print(f"  - {violation}")
        return 1
    print(
        "route gate: OK — every route declares a policy or holds a reviewed entry, "
        "and resolves under the central policy resolver"
    )
    return 0


def cmd_list() -> int:
    enumerated = _enumerate()
    entries = _entry_map(load_inventory())
    for route in enumerated:
        route_class = _route_class(route, entries)
        permission = (
            f" {route.declared.permission.value}"
            if route.declared and route.declared.permission
            else ""
        )
        print(f"{route.key:<70} {route_class:<16} {route.owner}{permission}")
    return 0


_PROPOSED_PUBLIC_AUTH = frozenset(
    {
        "GET /api/v1/auth/setup-status",
        "POST /api/v1/auth/setup",
        "POST /api/v1/auth/login",
        "POST /api/v1/auth/demo-login",
        "POST /api/v1/auth/mfa/verify",
        "POST /api/v1/auth/mfa/enroll",
        "POST /api/v1/auth/register",
        "POST /api/v1/auth/refresh",
        # Passkey sign-in: the assertion verifies the credential and the
        # account, then issues the session — same class as /auth/login
        # (regeneration must never demote it to session).
        "POST /api/v1/auth/passkeys/options",
        "POST /api/v1/auth/passkeys/verify",
        # OIDC entry points (declared public_auth on the routes; pinned here
        # so a re-generated inventory keeps the class even if a declaration
        # is ever dropped).
        "POST /api/v1/auth/sso/status",
        "POST /api/v1/auth/sso/authorize",
        "GET /api/v1/auth/sso/callback",
    }
)

_PROPOSED_PUBLIC_PATHS = frozenset(
    {
        "/",
        "/health",
        "/.well-known/smart-configuration",
        # Unauthenticated, non-credential data/metadata routes (proven by the
        # dependency-introspection gate — they carry no auth mechanism):
        "/api/v1/config/public",
        "/api/v1/ai-config/provider-presets",
        "/api/v1/concept-edges/schema",
        "/api/v1/notifications/vapid-public-key",
        "/api/v1/fhir/R4/metadata",
    }
)


def _proposed_class(route: EnumeratedRoute) -> RouteClass:
    """Heuristic principal class for a not-yet-declared route (triage only).

    The data file freezes the verdict; this heuristic exists so the baseline
    is generated honestly and the special classes are visible in its diff.
    Class semantics and their implied auth dependencies are documented on
    :class:`~app.core.authz.policy.RouteClass` and pinned by
    ``ROUTE_CLASS_DEPENDENCIES`` — an entry is never guessed, it is reviewed
    against the route's actual dependency.
    """
    if route.method == "WS":
        return RouteClass.WEBSOCKET
    if route.path in _PROPOSED_PUBLIC_PATHS:
        return RouteClass.PUBLIC
    if route.key in _PROPOSED_PUBLIC_AUTH:
        return RouteClass.PUBLIC_AUTH
    if route.path.startswith("/api/v1/fhir/"):
        return RouteClass.TOKEN_FHIR
    if route.path in {"/api/v1/oauth/token", "/api/v1/oauth/revoke"}:
        return RouteClass.TOKEN_OAUTH
    if route.path == "/api/v1/documents/{document_id}/download":
        return RouteClass.TOKEN_PRESIGN
    if route.path.endswith("/webhook/{integration_id}") or "/api/{integration_id}/" in route.path:
        return RouteClass.TOKENLESS_HMAC
    return RouteClass.SESSION


def cmd_propose() -> int:
    """Print the entries the gate is missing, as ready-to-paste JSON rows."""
    enumerated = _enumerate()
    entries = _entry_map(load_inventory())
    proposed = [
        route for route in enumerated if route.declared is None and route.key not in entries
    ]
    for route in proposed:
        print(
            f'{{"route": "{route.key}", "route_class": "{_proposed_class(route).value}", '
            f'"owner": "{route.owner}"}}'
        )
    return 1 if proposed else 0


def cmd_matrix() -> int:
    enumerated = _enumerate()
    inventory = load_inventory()
    violations = check_inventory(enumerated, inventory)
    if violations:
        print(
            "route gate is red — refusing to generate a matrix from a failing state",
            file=sys.stderr,
        )
        for violation in violations:
            print(f"  - {violation}", file=sys.stderr)
        return 1

    entries = _entry_map(inventory)
    by_class: dict[str, list[EnumeratedRoute]] = defaultdict(list)
    for route in enumerated:
        by_class[_route_class(route, entries)].append(route)

    role_values = [role.value for role in authz_roles.Role]
    lines: list[str] = [MATRIX_HEADER]
    lines.append("\n## Role → permission defaults\n")
    lines.append("| Permission | " + " | ".join(role_values) + " |")
    lines.append("|---|" + "---|" * len(role_values))
    for resource, group in authz_permissions.iter_permissions_by_resource():
        lines.append(f"| **{resource}** | " + " | " * len(role_values) + "|")
        for permission in group:
            cells = [
                "yes" if authz_roles.role_has(role, permission) else "—"
                for role in authz_roles.Role
            ]
            lines.append(f"| `{permission.value}` | " + " | ".join(cells) + " |")
    lines.append(
        "\nScope rules narrow who a permission reaches (system / tenant / own /"
        " grant / break-glass — `backend/app/core/authz/scopes.py`); the table is"
        " the holding defaults only. Deletes are ADMIN/SYSTEM_ADMIN in the"
        " baseline (ADR 0054 — Phase-0 tightening of the draft matrix).\n"
    )

    lines.append("## Route inventory\n")
    lines.append(f"{len(enumerated)} routes across {len(by_class)} principal classes.\n")
    for route_class in sorted(by_class):
        routes = sorted(by_class[route_class], key=lambda item: item.key)
        lines.append(f"### `{route_class}` — {len(routes)} routes\n")
        lines.append("| Route | Permission | Scope | Owner (endpoint module) |")
        lines.append("|---|---|---|---|")
        for route in routes:
            _cls, permission, scope = _resolved_cells(route, entries)
            lines.append(f"| `{route.key}` | `{permission}` | `{scope}` | {route.owner} |")
        lines.append("")
        lines.append(
            "The permission/scope columns come from the central resolver"
            " (`backend/app/core/authz/route_policy.py`); the per-route review"
            " table is `docs/dev/AUTHZ_ROUTE_POLICIES.md`.\n"
        )

    declared = sum(1 for route in enumerated if route.declared is not None)
    lines.append("## Route gate\n")
    lines.append(
        f"- allowlist entries: {len(inventory['entries'])} (routes not yet migrated"
        f" to declared policies; {declared} routes already declare)\n"
        f"- retired keys: {len(inventory['retired'])} (monotonic shrink — entries can"
        " only move to `retired`, never return)\n"
        "- a new route without a declared policy or an entry fails CI"
        " (`tests/test_authz_route_gate.py`)\n"
    )
    lines.append("## Access-scope taxonomy\n")
    lines.append(
        "`system` covers every tenant; `tenant` is one tenant; `own` is the"
        " caller's own records; `grant` is reach through an active care-team"
        " grant; break-glass is the audited, time-boxed `access_elevations`"
        " widening (ADR 0054 D1/D6), never a role permission.\n"
    )

    MATRIX_PATH.parent.mkdir(parents=True, exist_ok=True)
    MATRIX_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"matrix written: {MATRIX_PATH}")
    return 0


def render_policies_document(enumerated: list[EnumeratedRoute], inventory: dict) -> str:
    """Render ``AUTHZ_ROUTE_POLICIES.md`` — the per-route review artifact.

    Every route → principal class, required permission + scope (resolved by
    the central ``route_policy`` rules) and the owning module, grouped by
    module. Pure so the stability test can compare the rendered table with
    the file on disk.
    """
    entries = _entry_map(inventory)
    lines: list[str] = [POLICIES_HEADER]
    by_module: dict[str, list[EnumeratedRoute]] = defaultdict(list)
    for route in enumerated:
        by_module[route.owner or "?"].append(route)
    enforced = 0
    for module in sorted(by_module):
        routes = sorted(by_module[module], key=lambda item: item.key)
        lines.append(f"### `{module}`\n")
        lines.append("| Route | Class | Permission | Required scope | Rule |")
        lines.append("|---|---|---|---|---|")
        for route in routes:
            route_class = _route_class(route, entries)
            policy = resolve_route_policy(route.method, route.path, route_class)
            rule = resolve_route_rule(route.method, route.path, route_class)
            rule_name = rule.name if rule else "UNRESOLVED"
            if policy is None or policy.permission is None:
                permission_cell = "— (auth/class mechanism)"
                scope_cell = "—"
            else:
                permission_cell = f"`{policy.permission.value}`"
                scope_cell = f"`{policy.scope.value}`"
                enforced += 1
            lines.append(
                f"| `{route.key}` | `{route_class}` | {permission_cell} | "
                f"{scope_cell} | `{rule_name}` |"
            )
        lines.append("")

    lines.append("## Enforcement summary\n")
    lines.append(
        f"- {len(enumerated)} routes resolve under the central resolver; "
        f"{enforced} session routes enforce a permission + scope at the gate.\n"
        f"- {len(enumerated) - enforced} routes are class-mechanism or auth-only"
        " self-service (public metadata, auth bootstrap, token principals,"
        " WebSockets, per-user self-service).\n"
        "- A route that resolves to nothing is denied (fail closed) and fails"
        " `scripts/authz_inventory.py check`.\n"
    )
    return "\n".join(lines)


def cmd_policies() -> int:
    """Write ``AUTHZ_ROUTE_POLICIES.md`` — the per-route review artifact."""
    enumerated = _enumerate()
    inventory = load_inventory()
    violations = check_inventory(enumerated, inventory)
    if violations:
        print(
            "route gate is red — refusing to generate the policy table from a failing state",
            file=sys.stderr,
        )
        for violation in violations:
            print(f"  - {violation}", file=sys.stderr)
        return 1

    POLICIES_PATH.parent.mkdir(parents=True, exist_ok=True)
    POLICIES_PATH.write_text(render_policies_document(enumerated, inventory), encoding="utf-8")
    print(f"policies written: {POLICIES_PATH}")
    return 0


def cmd_generate() -> int:
    """Write the inventory file from the current route set (review the diff).

    Fully mechanical: entries are ``METHOD path`` keys with the heuristic
    class and the owning module. Curation happens by reviewing the diff —
    a wrong class in the file is a data fix, never a heuristic tweak.
    """
    enumerated = _enumerate()
    inventory = {
        "schema": 1,
        "rule": (
            "every route declares a policy or holds an entry; entries may only "
            "be removed into retired (monotonic shrink — ADR 0054)"
        ),
        "entries": sorted(
            (
                {
                    "route": route.key,
                    "route_class": _proposed_class(route).value,
                    "owner": route.owner,
                }
                for route in enumerated
                if route.declared is None
            ),
            key=lambda entry: entry["route"],
        ),
        "retired": [],
    }
    INVENTORY_PATH.write_text(
        json.dumps(inventory, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(f"inventory written: {INVENTORY_PATH} ({len(inventory['entries'])} entries)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Route inventory / authz matrix CLI")
    parser.add_argument(
        "command", choices=["check", "list", "matrix", "policies", "propose", "generate"]
    )
    args = parser.parse_args()
    commands = {
        "check": cmd_check,
        "list": cmd_list,
        "matrix": cmd_matrix,
        "policies": cmd_policies,
        "propose": cmd_propose,
        "generate": cmd_generate,
    }
    return commands[args.command]()


if __name__ == "__main__":
    raise SystemExit(main())
