#!/usr/bin/env python3
"""Generate the python-sdk model layer from the bridge schema (D11).

Reads ``../../backend/app/extensions/builtin/health_assistant_bridge/
schema/bridge-api.schema.json`` and emits
``python-sdk/health_assistant_bridge/generated_models.py`` — the payload
models, typed error codes and stream event types the schema declares with
``x-sdk: true``. Stdlib only; committed output; hand-edits are overwritten.

  python3 scripts/generate_python_models.py            # regenerate
  python3 scripts/generate_python_models.py --check    # CI drift gate
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parent.parent.parent
SCHEMA = REPO_ROOT / "backend" / "app" / "extensions" / "builtin" / "health_assistant_bridge" / "schema" / "bridge-api.schema.json"
OUT = HERE.parent / "python-sdk" / "health_assistant_bridge" / "generated_models.py"

HEADER = """\
# GENERATED by integrations/health-assistant-bridge/scripts/generate_python_models.py
# from bridge-api.schema.json (schemaVersion {version}). Source of truth is the
# schema; hand-edits are overwritten by regeneration (plan 32 ADR-0040 D11).
from typing import Any, Dict, List, Literal, Optional

from pydantic import BaseModel, Field
"""


def _unwrap_nullable(prop):
    """anyOf [T, null] → (T, nullable=True)."""
    if isinstance(prop.get("type"), list):
        rest = [t for t in prop["type"] if t != "null"]
        out = dict(prop)
        out["type"] = rest[0] if rest else "object"
        return out, True
    any_of = prop.get("anyOf")
    if isinstance(any_of, list) and {"type": "null"} in any_of:
        rest = [p for p in any_of if p != {"type": "null"}]
        if len(rest) == 1:
            merged = dict(prop)
            merged.pop("anyOf")
            merged.update(rest[0])
            return merged, True
    return prop, False


def _py_type(prop, components, quotes=False, wrap_optional=False):
    prop, nullable = _unwrap_nullable(prop)
    if "$ref" in prop:
        name = prop["$ref"].rsplit("/", 1)[1]
        assert name in components, f"dangling ref {name}"
        inner = f"'{name}'" if quotes else name
        if nullable or wrap_optional:
            return f"Optional[{inner}]"
        return inner
    t = prop.get("type")
    if t == "string":
        if "enum" in prop:
            inner = "Literal[" + ", ".join(json.dumps(v) for v in prop["enum"]) + "]"
        else:
            inner = "str"
    elif t == "integer":
        inner = "int"
    elif t == "number":
        inner = "float"
    elif t == "boolean":
        inner = "bool"
    elif t == "array":
        inner = f"List[{_py_type(prop.get('items', {}), components, quotes=True)}]"
    elif t == "object":
        inner = "Dict[str, Any]"
    else:
        raise AssertionError(f"unmapped property type: {prop}")
    if nullable or wrap_optional:
        return f"Optional[{inner}]"
    return inner


def _default(prop, required):
    _, nullable = _unwrap_nullable(prop)
    if "default" in prop and prop["default"] is not None:
        return f" = {json.dumps(prop['default'])}", False
    if required:
        return "", False
    if nullable:
        return " = None", False
    if prop.get("type") == "array":
        return " = Field(default_factory=list)", False
    return " = None", True


def _emit_component(name, comp, components, lines):
    lines.append(f"class {name}(BaseModel):")
    desc = comp.get("description")
    if desc:
        lines.append(f'    """{desc}"""')
    props = comp.get("properties", {})
    required = set(comp.get("required", []))
    if not props:
        lines.append("    pass")
        lines.append("")
        return
    for field, prop in props.items():
        default, wrap_optional = _default(prop, field in required)
        lines.append(f"    {field}: {_py_type(prop, components, wrap_optional=wrap_optional)}{default}")
    lines.append("")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true", help="fail when the generated module drifted (CI default)")
    group.add_argument("--update", action="store_true", help="rewrite the generated module")
    args = parser.parse_args()

    schema = json.loads(SCHEMA.read_text())
    components = schema["components"]
    sdk_components = {n: c for n, c in components.items() if c.get("x-sdk")}
    assert sdk_components, "no x-sdk components declared"

    error_codes = list(schema["errors"]["codes"].keys())
    event_names = []
    for name, comp in sdk_components.items():
        if name.endswith("Frame"):
            event = comp.get("examples", [{}])[0].get("event")
            assert event, f"{name} carries no event example"
            event_names.append((name, event))

    lines = [HEADER.format(version=schema["schemaVersion"]), ""]
    lines.append("BridgeErrorCode = Literal[" + ", ".join(json.dumps(c) for c in error_codes) + "]")
    lines.append("STREAM_EVENT_NAMES = Literal[" + ", ".join(json.dumps(e) for _n, e in sorted(event_names)) + "]")
    lines.append("BRIDGE_FEATURE_FLAGS = " + json.dumps(schema["handshake"]["featureFlags"]["vocabulary"]))
    lines.append("")
    for name in sorted(sdk_components):
        _emit_component(name, sdk_components[name], components, lines)
    rendered = "\n".join(lines).rstrip() + "\n"

    if args.update or not OUT.is_file():
        OUT.write_text(rendered, encoding="utf-8")
        print(f"generated {OUT.relative_to(HERE.parent.parent)} ({len(sdk_components)} models)")
        return 0
    committed = OUT.read_text(encoding="utf-8")
    if committed == rendered:
        print(f"generated models OK ({len(sdk_components)} models)")
        return 0
    print(
        f"python-sdk generated models DRIFT — run "
        f"`python3 scripts/generate_python_models.py` and commit the output",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
