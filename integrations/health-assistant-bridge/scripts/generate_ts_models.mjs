#!/usr/bin/env node
// Generate the ts-sdk model layer from the bridge schema (D11).
//
// Reads ../../backend/app/extensions/builtin/health_assistant_bridge/schema/
// bridge-api.schema.json and emits ../ts-sdk/src/generated-models.ts — the
// payload interfaces, typed error codes and stream event types the schema
// declares with `x-sdk: true`. Node-only, zero dependencies; committed
// output; hand-edits are overwritten.
//
//   node scripts/generate_ts_models.mjs            # regenerate
//   node scripts/generate_ts_models.mjs --check    // CI drift gate

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(HERE, "..", "..", "..");
const SCHEMA = path.join(
  REPO_ROOT,
  "backend",
  "app",
  "extensions",
  "builtin",
  "health_assistant_bridge",
  "schema",
  "bridge-api.schema.json",
);
const OUT = path.join(HERE, "..", "ts-sdk", "src", "generated-models.ts");

const HEADER = `// GENERATED by integrations/health-assistant-bridge/scripts/generate_ts_models.mjs
// from bridge-api.schema.json (schemaVersion VERSION). Source of truth is the
// schema; hand-edits are overwritten by regeneration (plan 32 ADR-0040 D11).
`;

function tsType(prop, components) {
  let nullable = false;
  let resolved = prop;
  if (Array.isArray(prop.type)) {
    nullable = prop.type.includes("null");
    resolved = { ...prop, type: prop.type.filter((t) => t !== "null")[0] ?? "object" };
  } else if (Array.isArray(prop.anyOf) && prop.anyOf.some((p) => JSON.stringify(p) === JSON.stringify({ type: "null" }))) {
    nullable = true;
    const rest = prop.anyOf.filter((p) => JSON.stringify(p) !== JSON.stringify({ type: "null" }));
    if (rest.length === 1) {
      resolved = { ...prop, ...rest[0] };
      delete resolved.anyOf;
    }
  }
  let inner;
  if (resolved.$ref) {
    const name = resolved.$ref.split("/").pop();
    if (!components[name]) throw new Error(`dangling ref: ${name}`);
    inner = name;
  } else if (resolved.type === "string") {
    inner = Array.isArray(resolved.enum)
      ? resolved.enum.map((v) => JSON.stringify(v)).join(" | ")
      : "string";
  } else if (resolved.type === "integer" || resolved.type === "number") {
    inner = "number";
  } else if (resolved.type === "boolean") {
    inner = "boolean";
  } else if (resolved.type === "array") {
    inner = `${tsType(resolved.items ?? {}, components)}[]`;
  } else if (resolved.type === "object") {
    inner = "Record<string, unknown>";
  } else {
    throw new Error(`unmapped property type: ${JSON.stringify(prop)}`);
  }
  return nullable ? `${inner} | null` : inner;
}

function emitComponent(name, comp, components, lines) {
  lines.push(`export interface ${name} {`);
  if (comp.description) {
    for (const line of comp.description.split("\n")) lines.push(`/** ${line.trim()} */`);
  }
  const required = new Set(comp.required ?? []);
  for (const [field, prop] of Object.entries(comp.properties ?? {})) {
    const opt = required.has(field) ? "" : "?";
    lines.push(`  ${field}${opt}: ${tsType(prop, components)};`);
  }
  lines.push(`}`);
  lines.push(``);
}

function main() {
  const check = process.argv.includes("--check");
  const schema = JSON.parse(readFileSync(SCHEMA, "utf8"));
  const components = schema.components;
  const sdkComponents = Object.fromEntries(
    Object.entries(components).filter(([, c]) => c["x-sdk"]),
  );
  if (Object.keys(sdkComponents).length === 0) throw new Error("no x-sdk components declared");

  const errorCodes = Object.keys(schema.errors.codes);
  const frames = Object.entries(sdkComponents)
    .filter(([name]) => name.endsWith("Frame"))
    .map(([name, comp]) => {
      const event = comp.examples?.[0]?.event;
      if (!event) throw new Error(`${name} carries no event example`);
      return { name, event };
    });

  const lines = [HEADER.replace("VERSION", String(schema.schemaVersion))];
  lines.push(`export type BridgeErrorCode =`);
  lines.push(`  ${errorCodes.map((c) => JSON.stringify(c)).join(" |\n  ")};`);
  lines.push(``);
  lines.push(`export type BridgeFeature =`);
  lines.push(
    `  ${schema.handshake.featureFlags.vocabulary.map((c) => JSON.stringify(c)).join(" |\n  ")};`,
  );
  lines.push(``);
  lines.push(`export type StreamEventName =`);
  lines.push(`  ${frames.map((f) => JSON.stringify(f.event)).sort().join(" |\n  ")};`);
  lines.push(``);
  lines.push(`export const BRIDGE_ERROR_CODES = [`);
  lines.push(`  ${errorCodes.map((c) => JSON.stringify(c)).join(",\n  ")},`);
  lines.push(`] as const;`);
  lines.push(``);
  lines.push(`export const STREAM_EVENT_NAMES = [`);
  lines.push(`  ${frames.map((f) => JSON.stringify(f.event)).sort().join(",\n  ")},`);
  lines.push(`] as const;`);
  lines.push(``);
  lines.push(
    `export const BRIDGE_FEATURE_FLAGS = ${JSON.stringify(schema.handshake.featureFlags.vocabulary)} as const;`,
  );
  lines.push(``);
  for (const name of Object.keys(sdkComponents).sort()) {
    emitComponent(name, sdkComponents[name], components, lines);
  }
  lines.push(`export type BridgeStreamEvent =`);
  lines.push(`  ${frames.map((f) => f.name).sort().join(" |\n  ")};`);
  const rendered = lines.join("\n").replace(/\n*$/, "\n");

  if (check) {
    const committed = readFileSync(OUT, "utf8");
    if (committed === rendered) {
      console.log(`generated models OK (${Object.keys(sdkComponents).length} models)`);
      return 0;
    }
    console.error(
      "ts-sdk generated models DRIFT — run `node scripts/generate_ts_models.mjs` and commit the output",
    );
    return 1;
  }
  writeFileSync(OUT, rendered, "utf8");
  console.log(
    `generated ${path.relative(REPO_ROOT, OUT)} (${Object.keys(sdkComponents).length} models)`,
  );
  return 0;
}

process.exit(main());
